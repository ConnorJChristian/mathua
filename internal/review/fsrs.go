package review

// FSRS for the fork (FSRS plan Phase 1). This file wraps the pure FSRS-6
// model in internal/fsrs (copied byte-for-byte from upstream) with the
// parts the reference scheduler, py-fsrs 6.3.2, adds on top of the
// formulas, and which upstream's engine integration got wrong or left out
// (local-data/qa/FSRS_UPSTREAM_ANALYSIS.md, items 3-5):
//
//   - The first review of a topic sets S = w[rating-1] and D = D0(rating),
//     exactly as the reference does for a new card. Upstream seeds S from the
//     SM-2 interval it has just written and applies an update on top, so its
//     first Good gives S = 1 and a 1-day interval where the reference gives
//     S = 2.3065 and 2 days.
//   - A review less than a day after the last one uses the FSRS-6 short-term
//     formula (w17..w19), as the reference does, not the long-term formula at
//     elapsed = 0 (where Good adds nothing and each Again cuts S by 5%).
//   - Elapsed time is whole days, as the reference's timedelta.days, so R at
//     a review is what the reference reads.
//   - The fork's parameters: the FSRS-6 default 21 weights, desired retention
//     0.9 and a maximum interval of 365 days (plan 3.8; upstream uses
//     36,500). No fuzz.
//
// Nothing here reads or writes a database or a clock: every function takes
// the values it needs and returns a value, so each one is pinned against
// the reference in fsrs_reference_test.go (tools/fsrs-reference/
// review_vectors.json, generated by generate_review_vectors.py from
// Scheduler.review_card, not from the formula methods). internal/fsrs is not
// modified: a fix that belongs there goes upstream first (plan 6.3).

import (
	"math"
	"time"

	"github.com/chuma-beep/mathua/internal/fsrs"
)

// Phase is where a topic's memory is in the FSRS card state machine, stored
// as fsrs_state. The reference has New, Learning, Review and Relearning;
// with no learning or relearning steps (the fork's configuration, and the
// one upstream's vectors were generated with) a card leaves Learning on its
// first review and never enters Relearning, so the reference's own state is
// "review" from the first review on. The fork records a lapse as
// PhaseRelearning until the next successful review, as information for the
// doctor and the reports; it changes no formula, because the reference's
// Review and Relearning branches compute the same thing without steps.
type Phase string

const (
	// PhaseNone: the topic has no FSRS state yet (a credited, placed or
	// never-reviewed row). Its retrievability is undefined and it is never
	// due on its own account (plan 3.4).
	PhaseNone Phase = "none"
	// PhaseReview: at least one review, the last of them not a lapse.
	PhaseReview Phase = "review"
	// PhaseRelearning: the last review was a lapse (Again).
	PhaseRelearning Phase = "relearning"
)

// Memory is one (learner, topic)'s FSRS state: the fsrs_* columns of
// concept_progress without the timestamps.
type Memory struct {
	Stability  float64
	Difficulty float64
	Reps       int
	Lapses     int
	Phase      Phase
}

// IsZero reports whether the memory has no FSRS state (PhaseNone, or the
// empty value a row without the columns scans to).
func (m Memory) IsZero() bool {
	return m.Phase == "" || m.Phase == PhaseNone
}

// Params is what the scheduler is configured with.
type Params struct {
	// Weights is the FSRS-6 parameter vector.
	Weights fsrs.Parameters
	// Retention is the desired recall probability an interval is chosen for.
	Retention float64
	// MaxInterval is the longest interval, in days.
	MaxInterval int
}

const (
	// DefaultRetention is the fork's desired retention (plan 3.8).
	DefaultRetention = 0.9
	// DefaultMaxInterval is the fork's maximum interval in days (plan 3.8):
	// a degree with a two-year horizon has no use for upstream's 36,500.
	DefaultMaxInterval = 365
)

// DefaultParams is the FSRS-6 default weights, retention 0.9 and a 365-day
// maximum interval.
func DefaultParams() Params {
	return Params{Weights: fsrs.DefaultParameters(), Retention: DefaultRetention, MaxInterval: DefaultMaxInterval}
}

func (p Params) retention() float64 {
	if p.Retention > 0 && p.Retention < 1 {
		return p.Retention
	}
	return DefaultRetention
}

func (p Params) maxInterval() int {
	if p.MaxInterval >= 1 {
		return p.MaxInterval
	}
	return DefaultMaxInterval
}

// Initial is the state after a topic's first review: S = w[rating-1],
// D = D0(rating), one repetition (a lapse if the rating is Again). This is
// the reference's Learning-state branch for a card with no stability.
func (p Params) Initial(rating fsrs.Rating) Memory {
	if !rating.Valid() {
		rating = fsrs.Good
	}
	m := Memory{
		Stability:  p.Weights.InitialStability(rating),
		Difficulty: p.Weights.InitialDifficulty(rating),
		Reps:       1,
		Phase:      PhaseReview,
	}
	if rating == fsrs.Again {
		m.Lapses = 1
		m.Phase = PhaseRelearning
	}
	return m
}

// Next is the long-term update: the state after a review elapsedDays after
// the last one (a day or more). elapsedDays is what the reference reads,
// whole days (ElapsedWholeDays); a negative value reads as 0 (R = 1).
func (p Params) Next(m Memory, rating fsrs.Rating, elapsedDays float64) Memory {
	if m.IsZero() {
		return p.Initial(rating)
	}
	if !rating.Valid() {
		return m
	}
	r := p.Retrievability(m, elapsedDays)
	out := m
	out.Stability = p.Weights.NextStability(m.Stability, m.Difficulty, r, rating)
	out.Difficulty = p.Weights.NextDifficulty(m.Difficulty, rating)
	return out.counted(rating)
}

// NextSameDay is the FSRS-6 short-term update, for a review less than a day
// after the last one:
//
//	S' = S * max(1, e^(w17 * (G - 3 + w18)) * S^(-w19))
//
// with the max(1, .) floor for Hard, Good and Easy only, so a same-day
// success never lowers stability and a same-day Again always does.
// Difficulty updates as in the long-term path. Retrievability plays no
// part, which is why the reference uses it: within a day R is near 1 and
// the long-term formula would give a success nothing and a lapse the full
// forgetting penalty.
func (p Params) NextSameDay(m Memory, rating fsrs.Rating) Memory {
	if m.IsZero() {
		return p.Initial(rating)
	}
	if !rating.Valid() {
		return m
	}
	w := p.Weights
	s := m.Stability
	if math.IsNaN(s) || math.IsInf(s, 0) || s < fsrs.StabilityMin {
		s = fsrs.StabilityMin
	}
	inc := math.Exp(w[17]*(float64(rating)-3+w[18])) * math.Pow(s, -w[19])
	if rating != fsrs.Again && inc < 1 {
		inc = 1
	}
	out := m
	out.Stability = s * inc
	if math.IsNaN(out.Stability) || math.IsInf(out.Stability, 0) || out.Stability < fsrs.StabilityMin {
		out.Stability = fsrs.StabilityMin
	}
	out.Difficulty = w.NextDifficulty(m.Difficulty, rating)
	return out.counted(rating)
}

func (m Memory) counted(rating fsrs.Rating) Memory {
	m.Reps++
	if rating == fsrs.Again {
		m.Lapses++
		m.Phase = PhaseRelearning
	} else {
		m.Phase = PhaseReview
	}
	return m
}

// Retrievability is the predicted recall probability elapsedDays after the
// last review. It is 1 at t <= 0 and 0 for a memory with no state (the
// reference returns 0 for a card never reviewed).
func (p Params) Retrievability(m Memory, elapsedDays float64) float64 {
	if m.IsZero() {
		return 0
	}
	if elapsedDays < 0 {
		elapsedDays = 0
	}
	return p.Weights.Retrievability(elapsedDays, m.Stability)
}

// IntervalFor is the next interval in days: the gap after which R falls to
// the desired retention, rounded half to even, clamped to [1, MaxInterval].
// A memory with no state has no interval (0).
func (p Params) IntervalFor(m Memory) int {
	return intervalFor(p.Weights, m, p.retention(), p.maxInterval())
}

// IntervalFor is the next interval for an explicit retention and maximum,
// with the default weights.
func IntervalFor(m Memory, retention float64, maxInterval int) int {
	return intervalFor(fsrs.DefaultParameters(), m, retention, maxInterval)
}

func intervalFor(w fsrs.Parameters, m Memory, retention float64, maxInterval int) int {
	if m.IsZero() {
		return 0
	}
	if maxInterval < 1 {
		maxInterval = DefaultMaxInterval
	}
	// internal/fsrs clamps to its own 36,500; the fork's cap is applied
	// here, on top, and is never larger than that.
	days := w.IntervalForRetention(m.Stability, retention)
	if days > maxInterval {
		return maxInterval
	}
	return days
}

// ElapsedWholeDays is the reference's elapsed time: whole days between the
// last review and now, rounded toward negative infinity like Python's
// timedelta.days. A review 23 hours after the last one is 0 days (the
// short-term path); 24 hours is 1.
func ElapsedWholeDays(last, now time.Time) float64 {
	return math.Floor(now.Sub(last).Hours() / 24)
}

// Review applies one review as the reference scheduler would: Initial for a
// topic with no state, NextSameDay when less than a whole day has passed
// since the last review, Next otherwise. It returns the elapsed whole days
// it used (0 for a first review) and the retrievability it read before the
// update (0 for a first review, 1 on the same day), for the review_log.
func (p Params) Review(m Memory, rating fsrs.Rating, lastReview, now time.Time) (next Memory, elapsedDays, retrievability float64) {
	if m.IsZero() || lastReview.IsZero() {
		return p.Initial(rating), 0, 0
	}
	elapsed := ElapsedWholeDays(lastReview, now)
	if elapsed < 1 {
		if elapsed < 0 {
			elapsed = 0
		}
		return p.NextSameDay(m, rating), elapsed, p.Retrievability(m, elapsed)
	}
	return p.Next(m, rating, elapsed), elapsed, p.Retrievability(m, elapsed)
}

// Package-level forms with the fork's default parameters.

// Initial is DefaultParams().Initial.
func Initial(rating fsrs.Rating) Memory { return DefaultParams().Initial(rating) }

// Next is DefaultParams().Next.
func Next(m Memory, rating fsrs.Rating, elapsedDays float64) Memory {
	return DefaultParams().Next(m, rating, elapsedDays)
}

// NextSameDay is DefaultParams().NextSameDay.
func NextSameDay(m Memory, rating fsrs.Rating) Memory { return DefaultParams().NextSameDay(m, rating) }

// Retrievability is DefaultParams().Retrievability.
func Retrievability(m Memory, elapsedDays float64) float64 {
	return DefaultParams().Retrievability(m, elapsedDays)
}
