// DailyCap is Phase 3's proposed daily review cap (plan 3.7, [C] 6).
const DailyCap = 25

func main() {
	dbPath := flag.String("db", "", "SQLite database (read through a copy)")
	student := flag.String("student", "", "one learner (default: every learner with a review_log)")
	nowFlag := flag.String("now", "", "the report's now (RFC3339)")
	days := flag.Int("days", 30, "forecast horizon in days")
	out := flag.String("out", "", "write the Markdown here (default stdout)")
	flag.Parse()
	if *dbPath == "" {
		fmt.Fprintln(os.Stderr, "usage: fsrs_shadow_report -db <path> [-student id] [-now RFC3339] [-days 30] [-out file.md]")
		os.Exit(2)
	}
	w := io.Writer(os.Stdout)
	if *out != "" {
		f, err := os.Create(*out)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		defer f.Close()
		w = f
	}
	if err := run(w, *dbPath, *student, *nowFlag, *days); err != nil {
		fmt.Fprintln(os.Stderr, "fsrs_shadow_report:", err)
		os.Exit(1)
	}
}

type report struct {
	w      io.Writer
	eng    *engine.Engine
	store  *storage.SQLiteStore
	db     *sql.DB
	dag    *concepts.DAG
	loc    *time.Location
	now    time.Time
	days   int
	params review.Params
}

func run(w io.Writer, dbPath, only, nowFlag string, days int) error {
	root := os.Getenv("MATHUA_ROOT")
	if root == "" {
		return fmt.Errorf("MATHUA_ROOT must name the install (its data/ and modules)")
	}
	copyPath, err := snapshotCopy(dbPath)
	if err != nil {
		return err
	}
	defer os.RemoveAll(filepath.Dir(copyPath))
	mods, err := modules.Default()
	if err != nil {
		return err
	}
	dag, err := concepts.LoadDirs(filepath.Join(root, "data", "concepts"), mods.ConceptDirs()...)
	if err != nil {
		return err
	}
	db, err := sql.Open("sqlite3", copyPath)
	if err != nil {
		return err
	}
	defer db.Close()
	now, err := reportNow(db, nowFlag)
	if err != nil {
		return err
	}
	defer clock.NewSim(now).Install()()
	store, err := storage.NewSQLiteStore(copyPath)
	if err != nil {
		return err
	}
	defer store.Close()
	planner, err := planning.Load(filepath.Join(root, "data", "courses.json"), dag, mods.CourseFiles()...)
	if err != nil {
		return err
	}
	eng := engine.New(store, dag, all.Registry(), nil, planner)
	eng.SetModules(mods)
	eng.SetFSRSMode(review.ModeShadow)
	rules, _ := review.CurrentRules()
	eng.SetFSRSRules(rules)
	loc, _ := review.LearnerZone()
	r := &report{w: w, eng: eng, store: store, db: db, dag: dag, loc: loc, now: now, days: days, params: review.DefaultParams()}
	students, err := r.students(only)
	if err != nil {
		return err
	}
	fmt.Fprintf(w, "# FSRS shadow report\n\n")
	fmt.Fprintf(w, "Generated by `scripts/fsrs_shadow_report` from `%s`, read-only. Now: %s (%s). Desired retention %.2f, maximum interval %d days, FSRS-6 default weights. Rules in force for the report's seeding: `%s`.\n\n",
		filepath.Base(dbPath), now.UTC().Format(time.RFC3339), now.In(loc).Format("2006-01-02 15:04 MST"), r.params.Retention, r.params.MaxInterval, rules)
	allErrs, err := store.FSRSErrors("")
	if err != nil {
		return err
	}
	fmt.Fprintf(w, "**fsrs_errors: %d rows** (events dropped from committed answers; the Phase 3 gate wants 0 over 14 days of shadow; `scripts/fsrs_doctor` lists them).\n\n", len(allErrs))
	if len(students) == 0 {
		fmt.Fprintln(w, "No learner has review_log rows: nothing to compare. Run with MATHUA_FSRS=shadow first.")
		return nil
	}
	for _, sid := range students {
		if err := r.learner(sid); err != nil {
			return fmt.Errorf("%s: %w", sid, err)
		}
	}
	return nil
}

// reportNow is -now, else 17:00 UTC the day after the last review_log row,
// else the wall clock.
func reportNow(db *sql.DB, flagNow string) (time.Time, error) {
	if flagNow != "" {
		t, err := time.Parse(time.RFC3339, flagNow)
		return t.UTC(), err
	}
	var last sql.NullString
	if err := db.QueryRow(`select max(at) from review_log`).Scan(&last); err == nil && last.Valid {
		if t, err := time.Parse(time.RFC3339Nano, last.String); err == nil {
			return t.UTC().Truncate(24 * time.Hour).Add(24*time.Hour + 17*time.Hour), nil
		}
	}
	return time.Now().UTC(), nil
}

func (r *report) students(only string) ([]string, error) {
	if only != "" {
		return []string{only}, nil
	}
	rows, err := r.db.Query(`select distinct student_id from review_log order by student_id`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var id string
		rows.Scan(&id)
		out = append(out, id)
	}
	return out, rows.Err()
}

func eventsOf(log []storage.ReviewLogEntry) []review.Event {
	ev := make([]review.Event, len(log))
	for i, e := range log {
		ev[i] = review.Event{At: e.At, Rating: fsrs.Rating(e.Rating), ElapsedDays: e.ElapsedDays, Source: e.Source, SAfter: e.SAfter, DAfter: e.DAfter, Held: e.Held}
	}
	return ev
}

func (r *report) learner(sid string) error {
	w := r.w
	progress, err := r.store.GetAllProgress(sid)
	if err != nil {
		return err
	}
	log, err := r.store.ReviewLogFor(sid, "")
	if err != nil {
		return err
	}
	byTopic := map[string][]storage.ReviewLogEntry{}
	for _, e := range log {
		byTopic[e.ConceptID] = append(byTopic[e.ConceptID], e)
	}
	skip := r.eng.ReviewExclusions(sid, progress)
	name := sid
	if st, err := r.store.GetStudent(sid); err == nil && st != nil && st.Name != "" {
		name = st.Name + " (`" + sid + "`)"
	}
	fmt.Fprintf(w, "## Learner %s\n\n", name)

	// Summary.
	bySource, held := map[string]int{}, map[string]int{}
	for _, e := range log {
		bySource[e.Source]++
		if e.Held != "" {
			held[e.Held]++
		}
	}
	seeds := map[string]int{}
	withState := 0
	for _, p := range progress {
		if m, _ := engine.FSRSMemory(p); !m.IsZero() {
			withState++
			seeds[p.FSRSSeed]++
		}
	}
	errs, err := r.store.FSRSErrors(sid)
	if err != nil {
		return err
	}
	fmt.Fprintf(w, "%d review_log rows (%s); %d held (%s). %d topics with FSRS state (seed: %s). %d fsrs_errors rows.\n\n",
		len(log), kv(bySource), sum(held), kv(held), withState, kv(seeds), len(errs))

	r.headline(sid, progress, skip)
	if err := r.perDay(sid, progress, byTopic, skip); err != nil {
		return err
	}
	r.calibration(log)
	r.forecast(sid, progress, skip)
	return nil
}

// headline is the first-day backlog: what FSRS would serve at now if it
// were switched on, against what the current rule says is due.
func (r *report) headline(sid string, progress map[string]*storage.ConceptProgress, skip map[string]bool) {
	w := r.w
	current := r.eng.DueReviewIDs(sid, "", progress, r.now)
	stored := r.eng.FSRSDueIDs(sid, progress, r.now, r.params.Retention)
	seeded := clone(progress)
	plan, none, err := r.eng.FSRSSeedPlan(sid, r.now)
	if err == nil {
		for _, s := range plan {
			p := *seeded[s.ConceptID]
			st, d, last := s.State.Stability, s.State.Difficulty, s.Last
			p.FSRSStability, p.FSRSDifficulty, p.FSRSLastReview = &st, &d, &last
			p.FSRSReps, p.FSRSLapses, p.FSRSState = s.State.Reps, s.State.Lapses, string(s.State.Phase)
			seeded[s.ConceptID] = &p
		}
	}
	after := r.eng.FSRSDueIDs(sid, seeded, r.now, r.params.Retention)
	fmt.Fprintf(w, "### First-day backlog if FSRS were switched on now\n\n")
	fmt.Fprintf(w, "| | Topics due |\n|---|---|\n")
	fmt.Fprintf(w, "| Current rule (`DueReviewIDs`) | %d |\n", len(current))
	fmt.Fprintf(w, "| FSRS, R < %.2f, state as stored | %d |\n", r.params.Retention, len(stored))
	fmt.Fprintf(w, "| FSRS after `scripts/fsrs_seed` (%d more topics seeded, %d mastered rows still without state) | **%d** |\n\n", len(plan), len(none), len(after))
	clear := (len(after) + DailyCap - 1) / DailyCap
	fmt.Fprintf(w, "With the proposed cap of %d a day, the backlog clears in %d day(s) before new dues are counted; spread over 7 days (plan 4.1) it is %.1f a day on top of the daily load.\n\n", DailyCap, clear, float64(len(after))/7)
	if len(after) > 0 {
		var parts []string
		for i, id := range after {
			if i == 12 {
				parts = append(parts, fmt.Sprintf("and %d more", len(after)-12))
				break
			}
			rr, _ := engine.FSRSRetrievabilityAt(seeded[id], r.now)
			parts = append(parts, fmt.Sprintf("`%s` R %.2f", id, rr))
		}
		fmt.Fprintf(w, "Lowest R first: %s.\n\n", strings.Join(parts, ", "))
	}
	both, onlyCur, onlyF := overlap(current, after)
	fmt.Fprintf(w, "Agreement at now: %d due under both rules, %d only under the current rule, %d only under FSRS.\n\n", both, onlyCur, onlyF)
}

func overlap(a, b []string) (both, onlyA, onlyB int) {
	inA := map[string]bool{}
	for _, x := range a {
		inA[x] = true
	}
	inB := map[string]bool{}
	for _, x := range b {
		inB[x] = true
		if inA[x] {
			both++
		} else {
			onlyB++
		}
	}
	for _, x := range a {
		if !inB[x] {
			onlyA++
		}
	}
	return
}

// perDay: for each learner-local day with activity, what the current rule
// served and what FSRS would have served at the day's start.
func (r *report) perDay(sid string, progress map[string]*storage.ConceptProgress, byTopic map[string][]storage.ReviewLogEntry, skip map[string]bool) error {
	w := r.w
	atts, err := r.store.GetAttemptsForStudent(sid)
	if err != nil {
		return err
	}
	type dayAgg struct {
		review, quiz map[string]bool
	}
	days := map[string]*dayAgg{}
	var first time.Time
	for _, a := range atts {
		if a.Source != "review" && a.Source != "quiz" {
			continue
		}
		d := string(review.LocalDay(a.Timestamp, r.loc))
		if days[d] == nil {
			days[d] = &dayAgg{review: map[string]bool{}, quiz: map[string]bool{}}
		}
		if a.Source == "review" {
			days[d].review[a.ConceptID] = true
		} else {
			days[d].quiz[a.ConceptID] = true
		}
	}
	for _, l := range byTopic {
		if len(l) > 0 && (first.IsZero() || l[0].At.Before(first)) {
			first = l[0].At
		}
	}
	if first.IsZero() {
		return nil
	}
	fmt.Fprintf(w, "### Per day: what the current rule served, what FSRS would have served\n\n")
	fmt.Fprintf(w, "Current rule: distinct topics answered in review sessions that day (and in the mastery check or a course test). FSRS: topics whose state, replayed from review_log up to the start of the day, had R < %.2f then, with the due rule's exclusions.\n\n", r.params.Retention)
	fmt.Fprintf(w, "| Day | Reviewed (current rule) | Checked | FSRS due at start | Both | Only current | Only FSRS |\n|---|---|---|---|---|---|---|\n")
	totals := [6]int{}
	for t := review.StartOfLocalDay(first, r.loc); !t.After(r.now); t = review.NextLocalDay(t, r.loc) {
		key := string(review.LocalDay(t, r.loc))
		var fsrsDue []string
		for cid, l := range byTopic {
			if skip[cid] || r.dag.Concept(cid) == nil {
				continue
			}
			var upto []storage.ReviewLogEntry
			for _, e := range l {
				if e.At.Before(t) {
					upto = append(upto, e)
				}
			}
			m, last, _ := review.ReplayLast(r.params, eventsOf(upto))
			if !m.IsZero() && r.params.Retrievability(m, review.ElapsedWholeDays(last, t)) < r.params.Retention {
				fsrsDue = append(fsrsDue, cid)
			}
		}
		var served []string
		agg := days[key]
		checked := 0
		if agg != nil {
			for c := range agg.review {
				served = append(served, c)
			}
			checked = len(agg.quiz)
		}
		if len(served) == 0 && len(fsrsDue) == 0 && checked == 0 {
			continue
		}
		b, oc, of := overlap(served, fsrsDue)
		fmt.Fprintf(w, "| %s | %d | %d | %d | %d | %d | %d |\n", key, len(served), checked, len(fsrsDue), b, oc, of)
		for i, v := range []int{len(served), checked, len(fsrsDue), b, oc, of} {
			totals[i] += v
		}
	}
	fmt.Fprintf(w, "| **Total** | %d | %d | %d | %d | %d | %d |\n\n", totals[0], totals[1], totals[2], totals[3], totals[4], totals[5])
	return nil
}

// calibration: predicted R at each logged event against its outcome.
func (r *report) calibration(log []storage.ReviewLogEntry) {
	w := r.w
	type bin struct {
		n, right int
		sumR     float64
	}
	var bins [10]bin
	var n, nDay, above, below int
	var ll, brier, llDay, brierDay float64
	for _, e := range log {
		if e.Source == "seed" || e.SBefore == 0 {
			continue // a first review predicts nothing
		}
		p := e.RAtReview
		y := 0.0
		if e.Rating > int(fsrs.Again) {
			y = 1
		}
		i := int(p * 10)
		if i > 9 {
			i = 9
		}
		if i < 0 {
			i = 0
		}
		bins[i].n++
		bins[i].sumR += p
		bins[i].right += int(y)
		q := math.Min(math.Max(p, 1e-4), 1-1e-4)
		l := -(y*math.Log(q) + (1-y)*math.Log(1-q))
		b := (p - y) * (p - y)
		n++
		ll += l
		brier += b
		if e.ElapsedDays >= 1 {
			nDay++
			llDay += l
			brierDay += b
		}
		if p >= 0.9 {
			above++
		} else {
			below++
		}
	}
	fmt.Fprintf(w, "### Calibration: predicted R against the outcome\n\n")
	if n == 0 {
		fmt.Fprintf(w, "No event with a prediction yet (only first reviews).\n\n")
		return
	}
	fmt.Fprintf(w, "Every logged event after a topic's first (held ones included: a held practice miss is a miss at its R). Outcome right = rating above Again. %d events: %d at R >= 0.9, %d below.\n\n", n, above, below)
	fmt.Fprintf(w, "| Predicted R | Events | Mean predicted | Observed right |\n|---|---|---|---|\n")
	for i, b := range bins {
		if b.n == 0 {
			continue
		}
		fmt.Fprintf(w, "| %d-%d%% | %d | %.3f | %.3f |\n", i*10, i*10+10, b.n, b.sumR/float64(b.n), float64(b.right)/float64(b.n))
	}
	fmt.Fprintf(w, "\n| | Events | Log loss | Brier |\n|---|---|---|---|\n")
	fmt.Fprintf(w, "| All | %d | %.4f | %.4f |\n", n, ll/float64(n), brier/float64(n))
	if nDay > 0 {
		fmt.Fprintf(w, "| A day or more after the last review | %d | %.4f | %.4f |\n", nDay, llDay/float64(nDay), brierDay/float64(nDay))
	}
	fmt.Fprintf(w, "\nSame-day events predict R = 1 by construction; the second row leaves them out. With predictions clipped to [0.0001, 0.9999], a same-day miss costs 9.2 nats of log loss.\n\n")
}

// forecast: expected reviews per day for the horizon under both rules,
// each due review answered right on its day.
func (r *report) forecast(sid string, progress map[string]*storage.ConceptProgress, skip map[string]bool) {
	w := r.w
	n := r.days
	cur := make([]int, n)
	fs := make([]int, n)
	fsSeeded := make([]int, n)
	seeded := clone(progress)
	if plan, _, err := r.eng.FSRSSeedPlan(sid, r.now); err == nil {
		for _, s := range plan {
			p := *seeded[s.ConceptID]
			st, d, last := s.State.Stability, s.State.Difficulty, s.Last
			p.FSRSStability, p.FSRSDifficulty, p.FSRSLastReview = &st, &d, &last
			p.FSRSReps, p.FSRSLapses, p.FSRSState = s.State.Reps, s.State.Lapses, string(s.State.Phase)
			seeded[s.ConceptID] = &p
		}
	}
	ids := make([]string, 0, len(progress))
	for id := range progress {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		if skip[id] || r.dag.Concept(id) == nil {
			continue
		}
		p := progress[id]
		// Current rule: the one due rule, then SM-2 after a right review.
		if mastery.Status(p.Status) == mastery.StatusMastered {
			row := review.Row{Status: mastery.StatusMastered}
			if p.LastReviewed != nil {
				row.LastReviewed = *p.LastReviewed
			}
			if p.LastAttempted != nil {
				row.LastAttempted = *p.LastAttempted
			}
			row.NextReviewDue = p.NextReviewDue
			sm := scheduler.SM2{Repetitions: p.SM2Repetitions, EFactor: p.SM2EFactor, Interval: p.SM2Interval}
			if sm.EFactor == 0 {
				sm.EFactor = 2.5
			}
			for d := 0; d < n; d++ {
				t := r.now.Add(time.Duration(d) * 24 * time.Hour)
				if review.IsDue(row, t) {
					cur[d]++
					sm = scheduler.ComputeSM2WithSpeed(sm, mastery.SM2Quality(true, 1.0), 1.0)
					days := sm.Interval
					if days < 1 {
						days = 1
					}
					next := t.AddDate(0, 0, days)
					row.LastReviewed, row.NextReviewDue = t, &next
				}
			}
		}
		simFSRS(r.params, progress[id], r.now, n, fs)
		simFSRS(r.params, seeded[id], r.now, n, fsSeeded)
	}
	fmt.Fprintf(w, "### Workload forecast, next %d days\n\n", n)
	fmt.Fprintf(w, "Reviews per day if every due review is done that day and answered right (current rule: the due date, then SM-2's interval; FSRS: due when R < %.2f, then the reference update for Good). No cap applied; days above the proposed cap of %d are marked.\n\n", r.params.Retention, DailyCap)
	fmt.Fprintf(w, "| Day | Date | Current rule | FSRS (as stored) | FSRS (after seeding) |\n|---|---|---|---|---|\n")
	var tc, tf, ts int
	for d := 0; d < n; d++ {
		t := r.now.Add(time.Duration(d) * 24 * time.Hour)
		mark := ""
		if fsSeeded[d] > DailyCap {
			mark = " (over cap)"
		}
		fmt.Fprintf(w, "| %d | %s | %d | %d | %d%s |\n", d, t.In(r.loc).Format("2006-01-02"), cur[d], fs[d], fsSeeded[d], mark)
		tc, tf, ts = tc+cur[d], tf+fs[d], ts+fsSeeded[d]
	}
	fmt.Fprintf(w, "| | **Total** | %d | %d | %d |\n\n", tc, tf, ts)
}

// simFSRS adds one topic's FSRS reviews over the horizon to counts.
func simFSRS(p review.Params, row *storage.ConceptProgress, now time.Time, n int, counts []int) {
	m, last := engine.FSRSMemory(row)
	if m.IsZero() || last.IsZero() {
		return
	}
	for d := 0; d < n; d++ {
		t := now.Add(time.Duration(d) * 24 * time.Hour)
		if p.Retrievability(m, review.ElapsedWholeDays(last, t)) < p.Retention {
			counts[d]++
			m, _, _ = p.Review(m, fsrs.Good, last, t)
			last = t
		}
	}
}

func clone(m map[string]*storage.ConceptProgress) map[string]*storage.ConceptProgress {
	out := make(map[string]*storage.ConceptProgress, len(m))
	for k, v := range m {
		out[k] = v
	}
	return out
}

func kv(m map[string]int) string {
	if len(m) == 0 {
		return "none"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		label := k
		if label == "" {
			label = "(none)"
		}
		parts[i] = fmt.Sprintf("%s %d", label, m[k])
	}
	return strings.Join(parts, ", ")
}

func sum(m map[string]int) int {
	t := 0
	for _, v := range m {
		t += v
	}
	return t
}

func snapshotCopy(dbPath string) (string, error) {
	if _, err := os.Stat(dbPath); err != nil {
		return "", err
	}
	src, err := sql.Open("sqlite3", "file:"+dbPath+"?mode=ro")
	if err != nil {
		return "", err
	}
	defer src.Close()
	dir, err := os.MkdirTemp("", "fsrs_shadow_report")
	if err != nil {
		return "", err
	}
	dst := filepath.Join(dir, "copy.db")
	if _, err := src.Exec("VACUUM INTO ?", dst); err != nil {
		os.RemoveAll(dir)
		return "", fmt.Errorf("copy database: %w", err)
	}
	return dst, nil
}
