// fsrs_shadow_report compares, on a Mathua database, what the current due
// rule did with what FSRS would do (FSRS plan Phase 2 and 6.2). It reads a
// copy and changes nothing. Markdown on stdout (or -out):
//
//   - per learner-local day: the topics the current rule served as reviews
//     (and in the mastery check), and the topics FSRS would have served at
//     the start of the day (R < 0.9 by the state replayed from review_log up
//     to then, with the due rule's exclusions: the floor, credit-only
//     foundations off the courses);
//   - calibration: the R predicted at each logged event against its outcome
//     (right = not Again), in 10% bins, with log loss and the Brier score,
//     and how many events fell above and below R = 0.9;
//   - a 30-day workload forecast under both rules (each due review assumed
//     answered right on its day), against the 25-topic daily cap Phase 3
//     proposes;
//   - the first-day backlog if FSRS were switched on at -now: the count
//     Phase 3's cap and spreading must absorb, as stored and after
//     scripts/fsrs_seed.
//
// Usage: MATHUA_ROOT=<install> go run ./scripts/fsrs_shadow_report -db <path>
// [-student id] [-now RFC3339] [-days 30] [-out file.md]. -now defaults to
// 17:00 UTC on the day after the last review_log row (for a replayed copy,
// the next session's time), else the wall clock.
